/** Maps category iconName to component */
export function getCategoryIcon(name: string, props?: IconProps) {
  const p = { ...defaultProps, ...props };
  switch (name) {
    case 'product': return <IconProduct {...p} />;
    case 'delivery': return <IconDelivery {...p} />;
    case 'packaging': return <IconPackaging {...p} />;
    case 'conversation': return <IconConversation {...p} />;
    case 'note': return <IconNote {...p} />;
    default: return <IconNote {...p} />;
  }
}
